"""
Mini-R1 Tokenizer Module
========================
Provides a lightweight, deterministic wrapper around a SentencePiece BPE model.

Why SentencePiece:
- Language-agnostic subword tokenization without external heuristic pre-tokenizers.
- Consistent handling of whitespace (using meta-symbol \u2581).
- Lossless detokenization: decode(encode(text)) reproduces original text formatting.
- Native support for user-defined symbols (<think>, </think>, <answer>, </answer>),
  guaranteeing that reasoning markup tokens remain atomic and never fragment.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Sequence
import sentencepiece as spm


# Reasoning and control tokens required across the Mini-R1 pipeline
DEFAULT_USER_DEFINED_SYMBOLS: list[str] = [
    "<think>",
    "</think>",
    "<answer>",
    "</answer>",
]


def train_sentencepiece(
    input_file: str | Path,
    model_prefix: str | Path,
    vocab_size: int = 8000,
    model_type: str = "bpe",
    user_defined_symbols: Sequence[str] = DEFAULT_USER_DEFINED_SYMBOLS,
    character_coverage: float = 1.0,
    unk_id: int = 0,
    bos_id: int = 1,
    eos_id: int = 2,
    pad_id: int = 3,
) -> Path:
    """
    Train a SentencePiece model from a text corpus.

    Args:
        input_file: Path to text file used for training.
        model_prefix: Output path prefix for generated .model and .vocab files.
        vocab_size: Target vocabulary size (approximate for small corpora).
        model_type: Subword algorithm ('bpe', 'unigram', 'char', 'word').
        user_defined_symbols: Special tokens that must never be split into subwords.
        character_coverage: Percentage of characters covered (1.0 for math/code).
        unk_id, bos_id, eos_id, pad_id: Deterministic special token IDs.

    Returns:
        Path to the saved .model file.
    """
    input_path = Path(input_file)
    if not input_path.exists():
        raise FileNotFoundError(f"Tokenizer training corpus not found: {input_path}")

    prefix_path = Path(model_prefix)
    prefix_path.parent.mkdir(parents=True, exist_ok=True)

    # Format user-defined symbols as comma-separated string for SentencePiece CLI API
    symbols_str = ",".join(user_defined_symbols)

    spm.SentencePieceTrainer.train(
        input=str(input_path),
        model_prefix=str(prefix_path),
        vocab_size=vocab_size,
        model_type=model_type,
        character_coverage=character_coverage,
        unk_id=unk_id,
        bos_id=bos_id,
        eos_id=eos_id,
        pad_id=pad_id,
        user_defined_symbols=symbols_str,
        byte_fallback=True,
        split_digits=True,
        add_dummy_prefix=False,
        remove_extra_whitespaces=False,
        normalization_rule_name="identity",
        hard_vocab_limit=False,
    )
    model_file = prefix_path.with_suffix(".model")
    if not model_file.exists():
        raise RuntimeError(f"SentencePiece training finished but model was not found at {model_file}")

    return model_file


class Tokenizer:
    """
    SentencePiece Tokenizer wrapper for Mini-R1.

    Encapsulates encoding, decoding, batching, and special token lookup
    with clear error handling and zero high-level framework dependencies.
    """

    def __init__(self, model_path: str | Path) -> None:
        """
        Initialize tokenizer from a trained .model file.

        Args:
            model_path: Path to the .model file generated by SentencePiece.
        """
        self.model_path = Path(model_path)
        if not self.model_path.exists():
            raise FileNotFoundError(
                f"Tokenizer model file does not exist at '{self.model_path}'. "
                f"Run 'python scripts/train_tokenizer.py' to train one first."
            )

        self._sp = spm.SentencePieceProcessor()
        if not self._sp.load(str(self.model_path)):
            raise RuntimeError(f"Failed to load SentencePiece model from {self.model_path}")

        # Cache special token IDs for high-frequency access during training/generation
        self._unk_id: int = self._sp.unk_id()
        self._bos_id: int = self._sp.bos_id()
        self._eos_id: int = self._sp.eos_id()
        self._pad_id: int = self._sp.pad_id()

        # Cache reasoning token IDs
        self._think_start_id: int = self._sp.piece_to_id("<think>")
        self._think_end_id: int = self._sp.piece_to_id("</think>")
        self._answer_start_id: int = self._sp.piece_to_id("<answer>")
        self._answer_end_id: int = self._sp.piece_to_id("</answer>")

    # -------------------------------------------------------------------------
    # Core API
    # -------------------------------------------------------------------------

    def encode(
        self,
        text: str,
        add_bos: bool = False,
        add_eos: bool = False,
    ) -> list[int]:
        """
        Encode a text string into a list of integer token IDs.

        Args:
            text: Input string to tokenize.
            add_bos: If True, prepend the BOS (Beginning of Sequence) token ID.
            add_eos: If True, append the EOS (End of Sequence) token ID.

        Returns:
            1D list of integer token IDs.
        """
        ids: list[int] = self._sp.encode_as_ids(text)
        if add_bos:
            ids = [self.bos_id] + ids
        if add_eos:
            ids = ids + [self.eos_id]
        return ids

    def decode(self, ids: Sequence[int]) -> str:
        """
        Decode a sequence of integer token IDs back into text string.

        SentencePiece automatically handles whitespace restoration
        and special token symbols.
        """
        # Filter out negative padding or boundary ids if any
        cleaned_ids = [int(i) for i in ids if int(i) >= 0]
        return self._sp.decode_ids(cleaned_ids)

    def encode_batch(
        self,
        texts: Sequence[str],
        add_bos: bool = False,
        add_eos: bool = False,
        pad: bool = False,
        max_length: int | None = None,
    ) -> list[list[int]]:
        """
        Encode a batch of strings into token IDs with optional padding.

        Args:
            texts: List or sequence of input strings.
            add_bos: Prepend BOS token ID to each sequence.
            add_eos: Append EOS token ID to each sequence.
            pad: If True, pad sequences to uniform length using pad_id.
            max_length: Maximum sequence length. If specified and pad=True,
                        pad to max_length (or truncate if longer).

        Returns:
            2D list of integer token IDs [batch_size, seq_len].
        """
        batch_ids = [self.encode(text, add_bos=add_bos, add_eos=add_eos) for text in texts]

        if not pad:
            return batch_ids

        # Determine target length for padding
        actual_max = max((len(seq) for seq in batch_ids), default=0)
        target_len = max_length if max_length is not None else actual_max

        padded_batch: list[list[int]] = []
        for seq in batch_ids:
            if len(seq) > target_len:
                # Truncate if exceeds target length
                padded_seq = seq[:target_len]
            else:
                # Pad to target length
                padded_seq = seq + [self.pad_id] * (target_len - len(seq))
            padded_batch.append(padded_seq)

        return padded_batch

    def vocab_size(self) -> int:
        """Return the actual total vocabulary size of the loaded model."""
        return self._sp.get_piece_size()

    def token_to_id(self, token: str) -> int:
        """Convert a subword string token to its corresponding integer ID."""
        return self._sp.piece_to_id(token)

    def id_to_token(self, token_id: int) -> str:
        """Convert an integer token ID to its subword piece string."""
        return self._sp.id_to_piece(token_id)

    # -------------------------------------------------------------------------
    # Special Token Properties
    # -------------------------------------------------------------------------

    @property
    def unk_id(self) -> int:
        """Unknown token ID."""
        return self._unk_id

    @property
    def bos_id(self) -> int:
        """Beginning-of-sequence token ID."""
        return self._bos_id

    @property
    def eos_id(self) -> int:
        """End-of-sequence token ID."""
        return self._eos_id

    @property
    def pad_id(self) -> int:
        """Padding token ID."""
        return self._pad_id

    @property
    def think_start_id(self) -> int:
        """Token ID for reasoning start tag <think>."""
        return self._think_start_id

    @property
    def think_end_id(self) -> int:
        """Token ID for reasoning end tag </think>."""
        return self._think_end_id

    @property
    def answer_start_id(self) -> int:
        """Token ID for answer start tag <answer>."""
        return self._answer_start_id

    @property
    def answer_end_id(self) -> int:
        """Token ID for answer end tag </answer>."""
        return self._answer_end_id

    def __len__(self) -> int:
        """Convenience method for len(tokenizer)."""
        return self.vocab_size()

    def __repr__(self) -> str:
        return f"Tokenizer(model_path='{self.model_path}', vocab_size={self.vocab_size()})"
